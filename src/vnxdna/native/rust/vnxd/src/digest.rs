//! Integrity primitives, standard library only (docs/V14_CONTRACTS.md §4).
//!
//! * [`crc32`]: zlib / IEEE 802.3 CRC-32 (reflected polynomial 0xEDB88320), the frame check of every persisted record;
//!   equal to Python's `zlib.crc32`.
//! * [`sha256`]: FIPS 180-4 SHA-256, the content digest of every stored generation; equal to Python's
//!   `hashlib.sha256`. It is an integrity check against accidental corruption and a binding between the mapping and
//!   the stored bytes; authenticity comes from the AES-GCM seal of the Python security layer, not from this hash.

const CRC_TABLE: [u32; 256] = crc_table();

const fn crc_table() -> [u32; 256] {
    let mut t = [0u32; 256];
    let mut n = 0;
    while n < 256 {
        let mut c = n as u32;
        let mut k = 0;
        while k < 8 {
            c = if c & 1 != 0 { (c >> 1) ^ 0xEDB8_8320 } else { c >> 1 };
            k += 1;
        }
        t[n] = c;
        n += 1;
    }
    t
}

pub fn crc32(data: &[u8]) -> u32 {
    let mut c = 0xFFFF_FFFFu32;
    for &b in data {
        c = CRC_TABLE[((c ^ b as u32) & 0xFF) as usize] ^ (c >> 8);
    }
    c ^ 0xFFFF_FFFF
}

