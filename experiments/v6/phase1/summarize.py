"""Render the Phase 1 results.json files as Markdown tables (summary.md). SIMULATED results only."""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ORDER = ["V5", "V6-int", "V6-rows255", "V6-plan-seq", "V6-adaptive"]


def grid(path: Path, key: str, label: str) -> str:
    d = json.loads(path.read_text())
    s = d["summary"]
    names = [n for n in ORDER if n in s]
    cells = sorted(next(iter(s.values())), key=float)
    out = [f"### {d['experiment']} — {d['label']}", "",
           f"commit `{d['provenance']['git_commit'][:7]}` (src dirty: {d['provenance']['worktree_dirty']}), "
           f"seeds {d['config']['seeds'][0]}…{d['config']['seeds'][-1]}, {d['decodes']} decodes, "
           f"false SUCCESS {d['false_success_total']}, wall {d['wall_seconds']} s", "",
           f"command: `{d['provenance']['command']}`", "",
           "| " + label + " | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    for c in cells:
        out.append(f"| {c} | " + " | ".join(f"{s[n][c]['success']}/{s[n][c]['trials']}" for n in names) + " |")
    thr = d["thresholds_all_trials_success"]
    out.append("| **threshold** | " + " | ".join(str(thr[n]) for n in names) + " |")
    out.append("")
    out.append("| configuration | strands (incl. superblock) | overhead (redundant strands incl. superblock / data strands) | encode s | median decode s (all cells) |")
    out.append("|---|---|---|---|---|")
    for n in names:
        c = d["setup"]["configs"][n]
        med = sorted(s[n][x]["median_decode_seconds"] for x in s[n])[len(s[n]) // 2]
        out.append(f"| {n} | {c['strands']} | {c['overhead_strands_per_data_strand']} | {c['encode_seconds']} | {med} |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    parts = ["# V6 Phase 1 results summary (SIMULATED)", "",
             "Generated by `experiments/v6/phase1/summarize.py` from the committed results.json files. Cells: trials "
             "with a SHA-256-verified SUCCESS / trials. Threshold: hardest cell value at which every trial succeeded "
             "and every easier cell did too.", ""]
    for name, key, label in (("P1-EXP-01-dropout", "dropout", "i.i.d. strand loss"),
                             ("P1-EXP-02-coverage", "coverage", "mean Poisson coverage"),
                             ("P1-EXP-03-burst", "burst_length", "burst length (strands) + 2 % i.i.d.")):
        p = HERE / name / "results.json"
        if p.exists():
            parts.append(grid(p, key, label))
    p = HERE / "P1-EXP-04-analytic" / "results.json"
    if p.exists():
        d = json.loads(p.read_text())
        parts += [f"### {d['experiment']} — {d['label']}", "",
                  f"commit `{d['provenance']['git_commit'][:7]}`, command: `{d['provenance']['command']}`", "",
                  "| size | configuration | K+M | D | Mc | order | overhead | p* (ε=1e-3) | p* (ε=1e-6) | burst tolerance |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for r in d["rows"]:
            g = r["geometry"]
            parts.append(f"| {r['size']} | {r['config']} | {g['K']}+{g['M']} | {g['D']} | {g['Mc']} | {g['order']} | "
                         f"{g['overhead']} | {r['iid_threshold_bound_eps_1e-3']} | {r['iid_threshold_bound_eps_1e-6']} | "
                         f"{r.get('burst_tolerance_strands', '—')} |")
        parts.append("")
    (HERE / "summary.md").write_text("\n".join(parts) + "\n")
    print((HERE / "summary.md").read_text())


if __name__ == "__main__":
    main()
