"""V13 disk-style metrics of the streaming encoder/decoder and the volume: software codec rates on this host
(SIMULATED strands and read pools; never physical DNA throughput). Writes <out>/stream-volume.json.

    PYTHONPATH=src python experiments/v13/bench/stream_volume_bench.py [--sizes 4,16] [--extent 1] [--out DIR] [--reps 3]

Measured (median of --reps, process peak RSS from the children's ru_maxrss where a subprocess runs, else this process):
  stream_encode   MB/s of encode_stream(file -> strands), 1 and 4 workers, extent --extent MiB
  stream_decode   MB/s of decode_stream by range (the encoder's file) and from a SIMULATED read pool (coverage 3, 1 %
                  substitutions) by archive ID, 1 and 4 workers
  volume_write    MB/s of Volume.write + flush (sequential), peak RSS
  volume_read     MB/s of a sequential read_at over the whole volume, cold (fresh open) and hot (cache)
  random_read     latency (ms, median and p95) of 4 KiB read_at at random offsets, cold and hot
Every number here comes from this script's JSON; the pools are generated by the tree on PYTHONPATH.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import random
import resource
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MIB = 1 << 20


def _git(tree: Path) -> str:
    return subprocess.run(["git", "-C", str(tree), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()


def _rss_mb() -> float:
    r = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    c = resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss / 1024
    return round(max(r, c), 1)


def _data(n: int, seed: int) -> bytes:
    return np.random.default_rng(seed).integers(0, 256, n, dtype=np.uint8).tobytes()


def _med(xs):
    return round(statistics.median(xs), 4)


def bench(size_mib: int, extent_mib: int, reps: int, work: Path) -> dict:
    from vnxdna.pipeline import stream as st
    from vnxdna.recovery.options import DecodeOptions
    from vnxdna.v4 import channel as ch
    from vnxdna.volume import Volume, VolumeOptions
    size = size_mib * MIB
    data = _data(size, 1000 + size_mib)
    src = work / f"in-{size_mib}.bin"
    src.write_bytes(data)
    out: dict = {"size_bytes": size, "extent_bytes": extent_mib * MIB, "load1_start": round(os.getloadavg()[0], 2)}
    # ---- stream encode
    for w in (1, 4):
        secs = []
        for r in range(reps):
            sink = work / f"s-{size_mib}-w{w}-{r}.fasta"
            t = time.perf_counter()
            st.encode_stream(src, sink, options=st.StreamOptions(extent_bytes=extent_mib * MIB, workers=w), overwrite=True)
            secs.append(time.perf_counter() - t)
            if r + 1 < reps:
                sink.unlink()
                sink.with_name(sink.name + ".stream.json").unlink()
        out[f"stream_encode_w{w}"] = {"seconds": _med(secs), "mb_s": round(size / _med(secs) / 1e6, 3), "reps": reps,
                                      "peak_rss_mb": _rss_mb()}
    sink = work / f"s-{size_mib}-w4-{reps - 1}.fasta"
    man = sink.with_name(sink.name + ".stream.json")
    # ---- stream decode by range and from a simulated pool
    pool = work / f"r-{size_mib}.fastq"
    ch.simulate_file(sink, pool, ch.ChannelConfig(seed=7, coverage=3, substitution_rate=0.01))
    for label, strands in (("range", sink), ("pool", pool)):
        for w in (1, 4):
            secs = []
            for r in range(reps):
                o = work / f"o-{size_mib}-{label}-w{w}.bin"
                t = time.perf_counter()
                rep = st.decode_stream(strands, man, o, options=DecodeOptions(workers=w), overwrite=True)
                secs.append(time.perf_counter() - t)
                assert o.read_bytes() == data
                o.unlink()
            out[f"stream_decode_{label}_w{w}"] = {"seconds": _med(secs), "mb_s": round(size / _med(secs) / 1e6, 3),
                                                  "reps": reps, "by_range": rep["by_range"], "by_pool": rep["by_pool"],
                                                  "peak_rss_mb": _rss_mb()}
    # ---- volume
    vdir = work / f"vol-{size_mib}"
    secs = []
    for r in range(reps):
        t = time.perf_counter()
        with Volume.create(vdir, VolumeOptions(extent_bytes=extent_mib * MIB), overwrite=True) as v:
            v.write(data)
            v.flush()
        secs.append(time.perf_counter() - t)
    out["volume_write"] = {"seconds": _med(secs), "mb_s": round(size / _med(secs) / 1e6, 3), "reps": reps, "peak_rss_mb": _rss_mb()}
    cold, hot = [], []
    for r in range(reps):
        with Volume.open(vdir, options=VolumeOptions(extent_bytes=extent_mib * MIB, cache_bytes=size + MIB)) as v:
            t = time.perf_counter()
            assert v.read_at(0, size) == data
            cold.append(time.perf_counter() - t)
            t = time.perf_counter()
            assert v.read_at(0, size) == data
            hot.append(time.perf_counter() - t)
            stat = v.stat()
    out["volume_read_cold"] = {"seconds": _med(cold), "mb_s": round(size / _med(cold) / 1e6, 3), "reps": reps,
                               "extents_decoded": stat["io"]["extents_decoded"]}
    out["volume_read_hot"] = {"seconds": _med(hot), "mb_s": round(size / _med(hot) / 1e6, 3), "reps": reps,
                              "cache_hits": stat["cache"]["hits"]}
    rng = random.Random(3)
    offsets = [rng.randrange(0, size - 4096) for _ in range(16)]
    lat_cold, lat_hot = [], []
    for off in offsets:
        with Volume.open(vdir, options=VolumeOptions(extent_bytes=extent_mib * MIB)) as v:
            t = time.perf_counter()
            b = v.read_at(off, 4096)
            lat_cold.append((time.perf_counter() - t) * 1e3)
            assert b == data[off:off + 4096]
            t = time.perf_counter()
            assert v.read_at(off, 4096) == b
            lat_hot.append((time.perf_counter() - t) * 1e3)
    out["random_read_4k"] = {"n": len(offsets), "cold_ms_median": _med(lat_cold),
                             "cold_ms_p95": round(sorted(lat_cold)[int(0.95 * (len(lat_cold) - 1))], 3),
                             "hot_ms_median": _med(lat_hot), "hot_ms_p95": round(sorted(lat_hot)[int(0.95 * (len(lat_hot) - 1))], 3)}
    out["load1_end"] = round(os.getloadavg()[0], 2)
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", default="4,16")
    ap.add_argument("--extent", type=int, default=1)
    ap.add_argument("--reps", type=int, default=3)
    ap.add_argument("--out", default=str(HERE / "stream-volume"))
    a = ap.parse_args(argv)
    import vnxdna
    from vnxdna.native import native_status
    out_dir = Path(a.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    doc = {"label": "SIMULATED (software codec rates on this host; strands are files)", "commit": _git(ROOT),
           "vnxdna": vnxdna.__version__, "python": platform.python_version(), "platform": platform.platform(),
           "cpu_count": os.cpu_count(), "native": {k: v["backend"] for k, v in native_status()["kernels"].items()},
           "extent_mib": a.extent, "reps": a.reps, "sizes": {}}
    with tempfile.TemporaryDirectory(prefix="vnxv13sv-", dir=os.environ.get("VNX_ARCH_TMP")) as tmp:
        for s in [int(x) for x in a.sizes.split(",")]:
            doc["sizes"][f"{s}MiB"] = bench(s, a.extent, a.reps, Path(tmp))
            print(json.dumps({f"{s}MiB": doc["sizes"][f"{s}MiB"]}), flush=True)
    (out_dir / "stream-volume.json").write_text(json.dumps(doc, indent=2) + "\n")
    print("saved", out_dir / "stream-volume.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
