#!/usr/bin/env python3
"""Generate hardware/h3-fpga/gf256_rom.vh: the GF(2^8) log/antilog ROMs.

The tables are generated from the primitive polynomial 0x11D (x^8+x^4+x^3+x^2+1),
the same field the software uses in ``src/vnxdna/codec/gf256.py``.  The
generated file is checked against the project's own tables by
``differential_check.py``.

Usage:  python3 gen_gf256_rom.py [output.vh]
"""
from __future__ import annotations

import sys
from pathlib import Path

PRIMITIVE_POLY = 0x11D
GENERATOR = 2


def build_tables() -> tuple[list[int], list[int]]:
    exp = [0] * 512
    log = [0] * 256
    x = 1
    for i in range(255):
        exp[i] = x
        log[x] = i
        x <<= 1
        if x & 0x100:
            x ^= PRIMITIVE_POLY
    for i in range(255, 512):
        exp[i] = exp[i - 255]
    return exp, log


def render(exp: list[int], log: list[int]) -> str:
    out: list[str] = []
    out.append("// GF(2^8) log/antilog ROMs, primitive polynomial 0x11D, generator 2.")
    out.append("//")
    out.append("// GENERATED by gen_gf256_rom.py -- do not edit by hand.")
    out.append("// The tables are identical to vnxdna.codec.gf256.EXP / vnxdna.codec.gf256.LOG")
    out.append("// (verified by differential_check.py), so a multiply computed here is")
    out.append("// bit-identical to gf256.mul() in the software reference.")
    out.append("//")
    out.append("// EXP holds alpha^0..alpha^254 and then repeats alpha^0..alpha^254, so")
    out.append("// EXP[255..509] == EXP[0..254] exactly as in the software table.  gf_mul")
    out.append("// indexes EXP[log[a]+log[b]] with no modular reduction, which is")
    out.append("// literally the software expression gf256.mul(a, b) = EXP[LOG[a]+LOG[b]].")
    out.append("//")
    out.append("// LOG holds log_2 of each non-zero field element; LOG[0] is never used")
    out.append("// (gf_mul short-circuits zero) and is written as 0.")
    out.append("")
    out.append("`ifndef GF256_ROM_VH")
    out.append("`define GF256_ROM_VH")
    out.append("")
    out.append("`define GF256_EXP_TOTAL 512")
    out.append("`define GF256_LOG_TOTAL 256")
    out.append("")
    out.append("function [7:0] gf_exp_rom(input [8:0] index);")
    out.append("    begin")
    out.append("        case (index)")
    for i in range(512):
        out.append("            9'd%-3d: gf_exp_rom = 8'h%02X;" % (i, exp[i]))
    out.append("            default: gf_exp_rom = 8'h00;")
    out.append("        endcase")
    out.append("    end")
    out.append("endfunction")
    out.append("")
    out.append("function [7:0] gf_log_rom(input [7:0] index);")
    out.append("    begin")
    out.append("        case (index)")
    for i in range(256):
        out.append("            8'd%-3d: gf_log_rom = 8'h%02X;" % (i, log[i]))
    out.append("            default: gf_log_rom = 8'h00;")
    out.append("        endcase")
    out.append("    end")
    out.append("endfunction")
    out.append("")
    out.append("`endif // GF256_ROM_VH")
    out.append("")
    return "\n".join(out)


def main() -> int:
    exp, log = build_tables()
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("gf256_rom.vh")
    out.write_text(render(exp, log), encoding="ascii")
    print(f"wrote {out} ({len(exp)} exp entries, {len(log)} log entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
